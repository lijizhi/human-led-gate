#!/usr/bin/env node
/**
 * Keeps the numbers in the docs true, by generating them instead of trusting a
 * human to remember.
 *
 * Why: every code change invalidates a batch of hand-written numbers. Across two
 * releases this repo was caught with "13 tests" when there were 17, "~150 lines"
 * when there were 184, then "~185 lines" when there were 281. A rule saying
 * "remember to update the docs" has a 0% success rate at that job. A generated
 * block has no memory to fail.
 *
 *   node scripts/doc-numbers.js           # rewrite the blocks in place
 *   node scripts/doc-numbers.js --check   # exit 1 if any block is stale
 *
 * Blocks are delimited so the script can find them:
 *
 *   <!-- generated:numbers -->
 *   ... anything ...
 *   <!-- /generated:numbers -->
 *
 * Everything between the markers is replaced. Add a block to any markdown file.
 *
 * What counts:
 *   tests        declared `test(` calls in test/*.js — declared, not the number
 *                that passed, so the figure is the same on every platform even
 *                when some cases are skipped off-Windows.
 *   hook lines   lines in hooks/pretooluse-gate.js
 *   deny rules   entries in DENY_RULES in bin/humanled.js
 */
const fs = require("fs");
const path = require("path");

// Resolve the repo from the working directory, not from this file's location, so
// the script can be pointed at any checkout (and tested against throwaway repos).
function findRepoRoot(start) {
  let dir = path.resolve(start);
  for (;;) {
    if (fs.existsSync(path.join(dir, ".git"))) return dir;
    const parent = path.dirname(dir);
    if (parent === dir) return path.resolve(start);
    dir = parent;
  }
}

const ROOT = findRepoRoot(process.cwd());
const CHECK = process.argv.includes("--check");
const START = "<!-- generated:numbers -->";
const END = "<!-- /generated:numbers -->";

function countTests() {
  const dir = path.join(ROOT, "test");
  let n = 0;
  for (const f of fs.readdirSync(dir)) {
    if (!f.endsWith(".js")) continue;
    const body = fs.readFileSync(path.join(dir, f), "utf8");
    // Declarations only: `test("...", () => {` and `test("...", {skip}, () => {`.
    n += (body.match(/^test\(/gm) || []).length;
  }
  return n;
}

function countLines(rel) {
  return fs.readFileSync(path.join(ROOT, rel), "utf8").split(/\r?\n/).length - 1;
}

function countDenyRules() {
  const body = fs.readFileSync(path.join(ROOT, "bin", "humanled.js"), "utf8");
  const block = /const DENY_RULES = \[([\s\S]*?)\];/.exec(body);
  if (!block) throw new Error("cannot find DENY_RULES in bin/humanled.js");
  return (block[1].match(/^\s*"/gm) || []).length;
}

function render() {
  const stats = {
    tests: countTests(),
    hookLines: countLines("hooks/pretooluse-gate.js"),
    denyRules: countDenyRules(),
  };
  return [
    START,
    `| Fact | Value |`,
    `|---|---|`,
    `| Declared hook-protocol tests | ${stats.tests} |`,
    `| \`hooks/pretooluse-gate.js\` | ${stats.hookLines} lines |`,
    `| Sandbox deny rules written by the installer | ${stats.denyRules} |`,
    ``,
    `_Generated by \`node scripts/doc-numbers.js\`. Do not edit these rows by hand:`,
    `\`--check\` fails the build when they drift._`,
    END,
  ].join("\n");
}

function markdownFiles() {
  const out = [];
  for (const entry of fs.readdirSync(ROOT)) {
    if (entry.endsWith(".md")) out.push(path.join(ROOT, entry));
  }
  const docs = path.join(ROOT, "docs");
  if (fs.existsSync(docs)) {
    for (const f of fs.readdirSync(docs)) {
      if (f.endsWith(".md")) out.push(path.join(docs, f));
    }
  }
  return out;
}

const replacement = render();
const stale = [];
let touched = 0;

for (const file of markdownFiles()) {
  const body = fs.readFileSync(file, "utf8");
  const start = body.indexOf(START);
  if (start === -1) continue;
  const end = body.indexOf(END, start);
  if (end === -1) {
    console.error(`${path.relative(ROOT, file)}: has ${START} with no ${END}`);
    process.exit(1);
  }
  const current = body.slice(start, end + END.length);
  if (current === replacement) continue;

  stale.push(path.relative(ROOT, file));
  if (!CHECK) {
    fs.writeFileSync(file, body.slice(0, start) + replacement + body.slice(end + END.length));
    touched += 1;
  }
}

if (CHECK) {
  if (stale.length) {
    console.error("Doc numbers are stale in:");
    for (const f of stale) console.error(`  ${f}`);
    console.error("\nRun `node scripts/doc-numbers.js` and commit the result.");
    process.exit(1);
  }
  console.log(`Doc numbers are current (${countTests()} tests, ${countLines("hooks/pretooluse-gate.js")} hook lines, ${countDenyRules()} deny rules).`);
} else {
  console.log(touched ? `Updated ${touched} file(s).` : "Nothing to update.");
}
